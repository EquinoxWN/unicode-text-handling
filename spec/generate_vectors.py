"""Build the shared test vectors (spec/vectors) and the Python grapheme table from Unicode 15.0.0 data.

usage: python spec/generate_vectors.py [--check]
Reads data/ucd/15.0.0 (downloaded and checksum-verified by fetch_ucd.py when missing). With --check,
nothing is written and the exit code is 1 if any committed file differs from what would be generated.
"""

from __future__ import annotations

import argparse
import itertools
import os
import sys
import tempfile
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fetch_ucd

ROOT = fetch_ucd.ROOT
DATA = fetch_ucd.DEFAULT_DEST
VECTORS = ROOT / "spec" / "vectors"
PY_TABLE = ROOT / "python" / "src" / "unicode_text_handling" / "_grapheme_data.py"
COLLATION_MEMBER = "CollationTest/CollationTest_NON_IGNORABLE_SHORT.txt"
COLLATION_STRIDE = 20
MAX_ROUNDS = 3
UNDEFINED_1252 = frozenset({0x81, 0x8D, 0x8F, 0x90, 0x9D})
MOJIBAKE_CLEAN = [
    "José",
    "山田太郎",
    "Müller",
    "naïve café",
    "“quoted” – dash",
    "€ 5",
    "👍🏽 ok",
    "Ærøskøbing",
    "Ελληνικά",
    "Đặng Thị",
    "Ārvis",
    "Ángel",
]
MOJIBAKE_UNCHANGED = ["", "plain ascii", "SÃO PAULO", "山田", "€100", "Ã", "naïve café"]


def header(title: str, source: str) -> list[str]:
    """Comment lines naming the generator and the Unicode source file."""
    return [
        f"# {title}",
        f"# Generated by spec/generate_vectors.py from Unicode {fetch_ucd.UNICODE_VERSION} {source}.",
        "# Source data (c) Unicode, Inc., Unicode License v3: see LICENSE-UNICODE.txt. Do not edit.",
    ]


def hexs(text: str) -> str:
    """Space-separated uppercase hex code points of text."""
    return " ".join(f"{ord(c):04X}" for c in text)


def unhex(field: str) -> str:
    """Text from space-separated hex code points."""
    return "".join(chr(int(h, 16)) for h in field.split())


def normalization(src: str) -> str:
    """NormalizationTest.txt reduced to '@part N' markers and 'c1;c2;c3;c4;c5' lines."""
    out = header("Normalization conformance cases (c1;c2;c3;c4;c5)", "NormalizationTest.txt")
    for line in src.splitlines():
        if line.startswith("@Part"):
            out.append(f"@part {line[5]}")
        elif line and not line.startswith("#"):
            fields = [f.strip() for f in line.split("#", 1)[0].split(";")][:5]
            if len(fields) != 5 or not all(fields):
                raise ValueError(f"bad NormalizationTest line: {line!r}")
            out.append(";".join(fields))
    return "\n".join(out) + "\n"


def grapheme_cases(src: str) -> list[list[str]]:
    """Expected clusters (as hex strings) for each GraphemeBreakTest line."""
    cases = []
    for line in src.splitlines():
        if not line.startswith("÷"):
            continue
        body = line.split("#", 1)[0].strip().strip("÷").strip()
        clusters = [" ".join(c.split("×")).split() for c in body.split("÷")]
        cases.append([" ".join(cps) for cps in clusters])
    return cases


def grapheme(src: str) -> str:
    """GraphemeBreakTest.txt as 'cluster|cluster' lines plus naive-count baselines."""
    cases = grapheme_cases(src)
    cp_ok = sum(all(len(c.split()) == 1 for c in case) for case in cases)
    u16_ok = sum(all(len(c.split()) == 1 and int(c, 16) <= 0xFFFF for c in case) for case in cases)
    out = header("Grapheme cluster cases: clusters separated by |", "GraphemeBreakTest.txt")
    out.append(
        "# Baselines: cases a 'one code point (or one UTF-16 unit) per character' split gets right."
    )
    out += [f"@baseline codepoint_exact {cp_ok}", f"@baseline utf16_exact {u16_ok}"]
    out += ["|".join(case) for case in cases]
    return "\n".join(out) + "\n"


def collation(src: str) -> str:
    """Every 20th line of the NON_IGNORABLE_SHORT order, without lone surrogates, plus baselines."""
    lines = [ln.strip() for ln in src.splitlines() if ln.strip() and not ln.startswith("#")]
    kept = [ln for ln in lines if not any(0xD800 <= int(h, 16) <= 0xDFFF for h in ln.split())]
    sample = kept[::COLLATION_STRIDE]
    texts = [unhex(ln) for ln in sample]
    pairs = list(itertools.pairwise(texts))
    cp_ok = sum(a <= b for a, b in pairs)
    u16_ok = sum(a.encode("utf-16-be") <= b.encode("utf-16-be") for a, b in pairs)
    out = header(
        f"Collation order: every {COLLATION_STRIDE}th line of CollationTest_NON_IGNORABLE_SHORT "
        f"({len(lines) - len(kept)} lone-surrogate lines dropped)",
        "CollationTest.zip",
    )
    out.append("# Each line sorts at or after the previous one under the DUCET (non-ignorable).")
    out.append("# Baselines: adjacent pairs that plain code point / UTF-16 order keeps in order.")
    out += [f"@baseline codepoint_in_order {cp_ok}", f"@baseline utf16_in_order {u16_ok}"]
    out += sample
    return "\n".join(out) + "\n"


def garble(text: str) -> str:
    """UTF-8 bytes read as Windows-1252 (WHATWG: undefined bytes map to U+0080..U+009F)."""
    out = []
    for b in text.encode("utf-8"):
        try:
            out.append(bytes([b]).decode("cp1252"))
        except UnicodeDecodeError:
            out.append(chr(b))
    return "".join(out)


def cp1252_byte(char: str) -> int | None:
    """The Windows-1252 (WHATWG) byte for char, or None when it has none."""
    if ord(char) in UNDEFINED_1252:
        return ord(char)
    try:
        return char.encode("cp1252")[0]
    except UnicodeEncodeError:
        return None


def is_fixed_point(text: str) -> bool:
    """True when one repair step would not change text (so expected results are unambiguous)."""
    codes = [cp1252_byte(c) for c in text]
    if any(b is None for b in codes):
        return True
    raw = bytes(b for b in codes if b is not None)
    try:
        return raw.decode("utf-8") == text
    except UnicodeDecodeError:
        return True


def mojibake() -> str:
    """Garbled/expected pairs for 1 to 4 rounds of mis-decoding, plus text that must stay unchanged."""
    out = header("Mojibake repair cases: input<TAB>expected<TAB>rounds<TAB>note", "data (none)")
    out[1] = "# Generated by spec/generate_vectors.py with Python's cp1252 codec (no Unicode data)."
    out[2] = "# Do not edit."
    out.append("# Fields are space-separated hex code points; an empty field is the empty string.")
    for clean in MOJIBAKE_CLEAN:
        if not is_fixed_point(clean):
            raise ValueError(f"sample {clean!r} would be changed by repair; pick another")
        text = clean
        for rounds in range(1, MAX_ROUNDS + 2):
            text = garble(text)
            expected = clean
            for _ in range(rounds - min(rounds, MAX_ROUNDS)):
                expected = garble(expected)
            note = f"{clean} garbled {rounds}x"
            out.append(f"{hexs(text)}\t{hexs(expected)}\t{min(rounds, MAX_ROUNDS)}\t{note}")
    for text in MOJIBAKE_UNCHANGED:
        if not is_fixed_point(text):
            raise ValueError(f"unchanged sample {text!r} is not a fixed point")
        out.append(f"{hexs(text)}\t{hexs(text)}\t0\tunchanged: {text or '(empty)'}")
    return "\n".join(out) + "\n"


def property_ranges(gbp: str, emoji: str) -> list[tuple[int, int, str]]:
    """Merged Grapheme_Cluster_Break ranges plus Extended_Pictographic as its own value."""
    ranges: list[tuple[int, int, str]] = []
    for text, wanted in ((gbp, None), (emoji, "Extended_Pictographic")):
        for line in text.splitlines():
            data = line.split("#", 1)[0].strip()
            if not data:
                continue
            cps, prop = (f.strip() for f in data.split(";"))
            if wanted is not None and prop != wanted:
                continue
            first, _, last = cps.partition("..")
            ranges.append((int(first, 16), int(last or first, 16), "ExtPict" if wanted else prop))
    ranges.sort()
    merged: list[tuple[int, int, str]] = []
    for lo, hi, prop in ranges:
        if merged and lo <= merged[-1][1]:
            raise ValueError(f"overlapping properties at U+{lo:04X}: {merged[-1][2]} and {prop}")
        if merged and lo == merged[-1][1] + 1 and prop == merged[-1][2]:
            merged[-1] = (merged[-1][0], hi, prop)
        else:
            merged.append((lo, hi, prop))
    return merged


def python_table(gbp: str, emoji: str) -> str:
    """Python module holding the grapheme break property ranges."""
    rows = property_ranges(gbp, emoji)
    out = [
        f'"""Grapheme_Cluster_Break ranges from Unicode {fetch_ucd.UNICODE_VERSION} '
        '(generated by spec/generate_vectors.py; do not edit)."""',
        "",
        f'UNICODE_VERSION = "{fetch_ucd.UNICODE_VERSION}"',
        "",
        "# (first, last, property); code points not listed are Other.",
        "RANGES: tuple[tuple[int, int, str], ...] = (",
    ]
    out += [f'    (0x{lo:04X}, 0x{hi:04X}, "{prop}"),' for lo, hi, prop in rows]
    out.append(")")
    return "\n".join(out) + "\n"


def build() -> dict[Path, str]:
    """Every generated file and its content."""
    fetch_ucd.fetch_all(DATA)

    def read(name: str) -> str:
        return (DATA / name).read_text(encoding="utf-8")

    with zipfile.ZipFile(DATA / "CollationTest.zip") as zf:
        coll = zf.read(COLLATION_MEMBER).decode("utf-8")
    return {
        VECTORS / "normalization.txt": normalization(read("NormalizationTest.txt")),
        VECTORS / "grapheme.txt": grapheme(read("GraphemeBreakTest.txt")),
        VECTORS / "collation.txt": collation(coll),
        VECTORS / "mojibake.tsv": mojibake(),
        PY_TABLE: python_table(read("GraphemeBreakProperty.txt"), read("emoji-data.txt")),
    }


def write_atomic(path: Path, text: str) -> None:
    """Write text via a temp file and rename, so a crash never leaves half a file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def main(argv: list[str] | None = None) -> int:
    """Generate or check the vectors."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if committed files are stale")
    args = parser.parse_args(argv)
    try:
        files = build()
    except (fetch_ucd.FetchError, OSError, ValueError, zipfile.BadZipFile) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    stale = [p for p, text in files.items() if not p.is_file() or p.read_text("utf-8") != text]
    for path in stale:
        rel = path.relative_to(ROOT).as_posix()
        if args.check:
            print(f"stale: {rel} (run python spec/generate_vectors.py)", file=sys.stderr)
        else:
            write_atomic(path, files[path])
            print(f"wrote {rel}")
    if args.check and stale:
        return 1
    print(f"vectors: {len(files)} files, {len(files) - len(stale)} already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
